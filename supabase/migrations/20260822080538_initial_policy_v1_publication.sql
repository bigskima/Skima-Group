- SKIMA may immediately alert the customer that the requested amount exceeds the recorded cylinder capacity;
- SKIMA may offer the recorded maximum as a correction;
- the customer must be shown the correction before payment or final order confirmation; and
- SKIMA should not silently change the quantity and charge the customer without confirmation.

If the customer believes the registered cylinder capacity is wrong, SKIMA may require the cylinder details to be corrected and, where appropriate, re-verified before a larger refill can be requested.

The final customer charge and partner settlement should reflect the approved actual billable quantity, not kilograms that were not supplied.

