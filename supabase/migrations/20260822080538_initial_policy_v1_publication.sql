  select id into partner_document_id from public.policy_documents where key='policy.partner.participation' and status='active';

  if customer_document_id is null or partner_document_id is null then
    raise exception 'canonical policy document records must exist before v1.0 publication';
  end if;

  if not exists(select 1 from public.policy_versions where policy_document_id=customer_document_id and version_label='1.0') then
    insert into public.policy_versions(
      policy_document_id,version_label,summary_content,full_content,content_format,content_hash,status,
      effective_from,effective_until,published_at,requires_reacceptance,source_url,source_reference,
      source_updated_at,metadata,created_by
    ) values(
      customer_document_id,'1.0',customer_summary,customer_content,'markdown',
      encode(digest(convert_to(customer_content,'UTF8'),'sha256'),'hex'),'published',
      publication_time,null,publication_time,false,
      'https://odd-magpie-adf.notion.site/SKIMA-Customer-Terms-of-Service-LPG-Service-Policy-3c0efdb226628149a9c0db36e126d8cc?pvs=74',
      'notion:3c0efdb2-2662-8149-a9c0-db36e126d8cc',publication_time,
      jsonb_build_object('bootstrap',true,'sourceSurface','public_notion_reference','canonicalVersion','1.0','sourceNormalizedForInAppReader',true),
      null
    ) returning id into customer_version_id;

    insert into public.policy_events(policy_document_id,policy_version_id,event_type,actor_user_id,source,idempotency_key,metadata,occurred_at)
    values
      (customer_document_id,customer_version_id,'policy.version_created',null,'skima.policy.bootstrap','policy.customer.terms:v1.0:created',jsonb_build_object('versionLabel','1.0','createdVersionId',customer_version_id),publication_time),
      (customer_document_id,customer_version_id,'policy.version_published',null,'skima.policy.bootstrap','policy.customer.terms:v1.0:published',jsonb_build_object('reason','Initial canonical in-app publication','contentHash',encode(digest(convert_to(customer_content,'UTF8'),'sha256'),'hex')),publication_time)
    on conflict (source,idempotency_key) do nothing;
  end if;

  if not exists(select 1 from public.policy_versions where policy_document_id=partner_document_id and version_label='1.0') then
    insert into public.policy_versions(
      policy_document_id,version_label,summary_content,full_content,content_format,content_hash,status,
      effective_from,effective_until,published_at,requires_reacceptance,source_url,source_reference,
      source_updated_at,metadata,created_by
    ) values(
      partner_document_id,'1.0',partner_summary,partner_content,'markdown',
      encode(digest(convert_to(partner_content,'UTF8'),'sha256'),'hex'),'published',
      publication_time,null,publication_time,false,
      'https://odd-magpie-adf.notion.site/SKIMA-Partner-Participation-Terms-Public-Policy-3c0efdb22662814a944cd3dba9d6d11c?source=copy_link',
      'notion:3c0efdb2-2662-814a-944c-d3dba9d6d11c',publication_time,
      jsonb_build_object('bootstrap',true,'sourceSurface','public_notion_reference','canonicalVersion','1.0','sourceNormalizedForInAppReader',true),
      null
    ) returning id into partner_version_id;

    insert into public.policy_events(policy_document_id,policy_version_id,event_type,actor_user_id,source,idempotency_key,metadata,occurred_at)
    values
      (partner_document_id,partner_version_id,'policy.version_created',null,'skima.policy.bootstrap','policy.partner.participation:v1.0:created',jsonb_build_object('versionLabel','1.0','createdVersionId',partner_version_id),publication_time),
      (partner_document_id,partner_version_id,'policy.version_published',null,'skima.policy.bootstrap','policy.partner.participation:v1.0:published',jsonb_build_object('reason','Initial canonical in-app publication','contentHash',encode(digest(convert_to(partner_content,'UTF8'),'sha256'),'hex')),publication_time)
    on conflict (source,idempotency_key) do nothing;
  end if;
end;
$bootstrap$;
